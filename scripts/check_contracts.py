"""Regenerate deterministic contracts in a private copy and compare all bytes."""

from __future__ import annotations

import shutil
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def check_generated(root: Path) -> None:
    with tempfile.TemporaryDirectory(prefix="sledra-contract-check-") as tmp:
        copy = Path(tmp) / "spec"
        shutil.copytree(root / "spec", copy, ignore=shutil.ignore_patterns("__pycache__"))
        directories = (Path("1.0.0"), Path("fixtures/1.0.0"))
        for relative in directories:
            shutil.rmtree(copy / relative)
        for script in ("build_contract.py", "build_fixtures.py"):
            subprocess.run([sys.executable, str(copy / script)], check=True)
        errors = []
        checked = 0
        for relative in directories:
            source = root / "spec" / relative
            generated = copy / relative
            names = {p.relative_to(source) for p in source.rglob("*") if p.is_file()}
            names |= {p.relative_to(generated) for p in generated.rglob("*") if p.is_file()}
            for name in sorted(names):
                checked += 1
                if not (source / name).is_file() or not (generated / name).is_file():
                    errors.append(f"spec/{relative / name}: generated file inventory differs")
                elif (source / name).read_bytes() != (generated / name).read_bytes():
                    errors.append(f"spec/{relative / name}: generated bytes differ")
        for directory, expected in (
            ("recorder/event/contract", {"event-types.json", "event.schema.json"}),
            (
                "analysis/src/sledra_analysis/resources/contract",
                {
                    "event-types.json",
                    "event.schema.json",
                    "definition_manifest.schema.json",
                    "run_context.schema.json",
                    "attempt_context.schema.json",
                    "job_ref.schema.json",
                },
            ),
            (
                "recorder/internal/speccontract/contract",
                {p.name for p in (copy / "1.0.0").glob("*.json")},
            ),
        ):
            embedded = root / directory
            names = {p.name for p in embedded.glob("*.json")}
            if names != expected:
                errors.append(f"{directory}: unexpected embedded resource inventory")
            for name in sorted(names & expected):
                if (embedded / name).read_bytes() != (copy / "1.0.0" / name).read_bytes():
                    errors.append(f"{directory}/{name}: differs from canonical spec")
        metadata = tomllib.loads((root / "pyproject.toml").read_text())
        pin = (root / "spec/requirements-test.txt").read_text().strip()
        if pin not in metadata["dependency-groups"]["dev"]:
            errors.append("spec/requirements-test.txt: differs from canonical developer dependency")
        if errors:
            raise ValueError("\n".join(errors))
        print(
            f"Generated contract/fixture bytes match: {checked} files; embedded event and context resources match"
        )


if __name__ == "__main__":
    check_generated(ROOT)
